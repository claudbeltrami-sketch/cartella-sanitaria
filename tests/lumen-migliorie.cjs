/* Run: node tests/lumen-migliorie.cjs — synthetic data only, no clinical archive. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root={lumenStorage:{checkPacket(data){if(data.lumen_prova)throw Error('Archivio reale non accetta dati PROVA');}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'..','lumen-migliorie-prova.js'),'utf8'),{window:root});
const {promemoria,scadenze,validaBackup}=root.lumenMigliorieProva;
assert.equal(promemoria({}).empty,true,'cartella vuota non segnalata');
const incomplete=promemoria({nome:'TEST',cognome:'FITTIZIO',protocollo:['AUDIOMETRIA','SPIROMETRIA BASALE','VISIOTEST','ANALISI EMATOCHIMICHE']});
assert.equal(incomplete.missing.length,5,'firma, giudizio e tre prove');
assert.equal(incomplete.manual[0],'ANALISI EMATOCHIMICHE');
const completed=promemoria({nome:'TEST',cognome:'FITTIZIO',giudizio:'IDONEO',firma_lavoratore_png:'data:...',protocollo:['AUDIOMETRIA','SPIROMETRIA BASALE','VISIOTEST'],audio_dx_500:'20',spirometria_fev1:'2.5',visiotest_esito:'NORMALE'});
assert.equal(completed.missing.length,0);
const tally=scadenze([{days:-5,issues:[]},{days:0,issues:[]},{days:30,issues:[]},{days:31,issues:[]},{days:12,issues:['data mancante']},{days:-3,issues:[],ceased:true}]);
assert.equal(tally.overdue,1);
assert.equal(tally.next30,2);
assert.equal(tally.incomplete,1);
const payload={tipo:'BELTRAMI_BACKUP_LEGGERO_V2',versione:2,allegatiSeparati:true,creato:'2026-10-23T18:00:00.000Z',contenuto:{cartelle:[{data:{cognome:'TEST'}}],originali:[],localStorage:{}}};
assert.equal(validaBackup(payload).mode,'leggero');
assert.equal(validaBackup({...payload,tipo:'BELTRAMI_BACKUP_COMPLETO_V1',versione:1}).mode,'completo');
assert.throws(()=>validaBackup({...payload,contenuto:{cartelle:[],originali:[],localStorage:null}}));
assert.throws(()=>validaBackup({...payload,lumen_prova:true}));
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const service=fs.readFileSync(path.join(__dirname,'..','lumen-sw.js'),'utf8');
for(const id of ['lumenMiniControllo','lumenMiniScadenzeText','lumenMiniScadenzeAggiorna','lumenBackupUltimoVerificato','lumenBackupVerificaFile','lumenBackupFileDaVerificare'])assert.ok(html.includes('id="'+id+'"'),id);
assert.ok(html.includes('src="lumen-migliorie-prova.js?v=20261023-prova-1"'));
assert.ok(service.includes("ASSETS.push('lumen-migliorie-prova.js')"));
console.log('OK — LUMEN migliorie: 16 controlli con soli dati sintetici.');
